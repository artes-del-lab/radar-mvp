# Коды ОКПД2, которые нас интересуют. Код тендера подходит, если начинается
# с одного из префиксов.
OKPD2_INCLUDE = [
    "28.92",  # машины для горных работ и строительства
    "29.10",  # автотранспортные средства (автокраны, грузовики, спецтехника)
    "28.30",  # сельхозтехника: тракторы, а также комбайны и прочие машины
]

# Исключения внутри включённых групп — проверяются первыми.
OKPD2_EXCLUDE = [
    "29.10.2",  # легковые автомобили
    "29.10.3",  # автобусы
]


def okpd2_matches(code: str) -> bool:
    """Попадает ли код ОКПД2 в целевые группы с учётом исключений."""
    code = code.strip()
    if any(code.startswith(prefix) for prefix in OKPD2_EXCLUDE):
        return False
    return any(code.startswith(prefix) for prefix in OKPD2_INCLUDE)


